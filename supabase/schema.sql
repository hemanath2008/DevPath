  updated_at timestamptz not null default now()
);

create table if not exists public.alternative_approaches (
  id bigint generated by default as identity primary key,
  language_id text not null references public.languages(id) on delete cascade,
  topic_id text not null references public.topics(id) on delete cascade,
  title text not null,
  idea text not null,
  code text not null,
  explanation text not null default '',
  time_complexity text not null default '',
  space_complexity text not null default '',
  advantages text[] not null default '{}'::text[],
  disadvantages text[] not null default '{}'::text[],
  when_to_use text not null default '',
  order_index integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.practice_questions (
