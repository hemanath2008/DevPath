create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.languages (
  id text primary key,
  display_name text not null,
  file_extension text not null,
  comment_syntax text not null,
  execution_runtime text not null,
  compiled boolean not null default false,
  tier smallint not null check (tier in (1, 2, 3)),
  sort_order integer not null default 0,
  supports_stdin boolean not null default true,
  supports_packages boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  human_language text not null default 'en',
  preferred_programming_language_id text references public.languages(id) on delete set null,
  xp integer not null default 0,
  streak integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.topics (
  id text primary key,
  title text not null,
  description text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  language_id text not null references public.languages(id) on delete cascade,
  topic_id text not null references public.topics(id) on delete cascade,
  title text not null,
  slug text not null unique,
  content jsonb not null default '{}'::jsonb,
  order_index integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.syntax_examples (
  id bigint generated by default as identity primary key,
