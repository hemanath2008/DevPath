create table if not exists public.learning_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  language_id text not null references public.languages(id) on delete cascade,
  topic_id text not null references public.topics(id) on delete cascade,
  status text not null default 'not_started',
  progress_percent integer not null default 0 check (progress_percent between 0 and 100),
  xp_earned integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, language_id, topic_id)
);

create table if not exists public.practice_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  practice_question_id bigint not null references public.practice_questions(id) on delete cascade,
  language_id text not null references public.languages(id) on delete cascade,
  submitted_code text not null default '',
  submitted_input text not null default '',
  submitted_output text not null default '',
  passed boolean not null default false,
  score numeric(5, 2) not null default 0,
  feedback jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.code_explanations (
  id bigint generated by default as identity primary key,
